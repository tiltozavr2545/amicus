-- Последний шаг перехода на множественные медиа: переносит одиночное
-- posts.image_path в post_media (позиция 0) и удаляет саму колонку —
-- единый источник правды, без второй копии данных о фото поста.
--
-- media_type захардкожен 'image' для бэкафилла намеренно, не догадка: до
-- этой миграции видео не поддерживалось вовсе, так что единственное фото
-- каждого поста было именно фото. created_at переиспользуется из самой
-- строки posts, а не now(): у бэкафилленной строки нет собственного момента
-- загрузки, а время поста — не менее правдиво и не даёт null.
--
-- Порядок операций: сначала перенос данных, потом снятие
-- posts_has_content — она бы не пережила модель "фото/видео в отдельных
-- запросах" (см. комментарий ниже), поэтому не переносится в эквивалентную
-- форму, а снимается осознанно.
insert into public.post_media (post_id, position, media_type, storage_path, created_at)
select id, 0, 'image', image_path, created_at
from public.posts
where image_path is not null;

-- Инвариант "текст или фото" был возможен как CHECK, пока оба поля писались
-- одним INSERT. С post_media фото/видео добавляются отдельными запросами
-- после вставки строки posts (id ещё не известен клиенту заранее), так что
-- транзакционно это на уровне БД без RPC-обёртки не проверить. Пустой пост
-- (ни текста, ни медиа) не дыра безопасности — просто мусор, который можно
-- удалить, — так что инвариант сознательно понижается до чисто клиентской
-- проверки (create_post_screen.dart), а не переносится в эквивалентную
-- форму.
alter table public.posts drop constraint if exists posts_has_content;
alter table public.posts drop column image_path;
