-- Бакет `media` заводится миграцией, а не только руками в дашборде.
--
-- 20260709134154 и 20260820130000 настраивают бакет через
-- `update storage.buckets … where id = 'media'`. Обе исходят из того, что он
-- уже существует, — и это верно для боевого проекта, где его создали руками в
-- июле 2026-го, но неверно для любого другого. Сам бакет не заводит ни одна
-- миграция.
--
-- 20260820130000 писала прямым текстом, зачем ограничения вернули в
-- репозиторий: «Пересборка проекта из миграций воспроизвела бы состояние, в
-- котором видео не загружается вовсе». Довод правильный, но доведён до
-- половины: она починила ЗНАЧЕНИЯ, оставив снаружи объект, к которому они
-- относятся. На чистом проекте оба `update` не находят ни одной строки и
-- отрабатывают успешно — миграции проходят «зелёными», а загрузка не работает,
-- и по логам наката понять это нельзя.
--
-- Вторая половина хуже первой. `public` нигде не зафиксирован, а на нём стоит
-- вся защита файлов: четыре SELECT-политики (аватарки — 20260712120000, фото
-- постов — 20260726180000) имеют смысл, только пока объект нельзя скачать по
-- прямой ссылке без токена. Публичный бакет отменяет их все разом, молча и
-- целиком. При создании бакета руками в дашборде это ровно один переключатель,
-- и ошибиться в нём нечем — он просто не в том положении.
--
-- Поэтому здесь `insert … on conflict do update`, а не ещё один `update`:
--
--   * на чистом проекте бакет создаётся с нужными значениями сразу;
--   * на боевом это no-op по значениям (проверено перед накатом: `public` уже
--     false, лимит 104857600, список MIME совпадает дословно);
--   * а `do update` делает `public = false` не «начальным значением», а
--     инвариантом, который повторный накат восстановит, если его когда-нибудь
--     переключат мимо репозитория.
--
-- Значения — те же, что стоят в боевом бакете и в 20260820130000; здесь они
-- повторяются не ради изменения, а чтобы строка была самодостаточной: смысл
-- этой миграции в том, что после неё бакет можно собрать с нуля, ничего не
-- зная о предыдущих.
--
-- `name` обязателен и равен id — так его завёл дашборд, так его ждёт Storage
-- API. Остальные колонки (`type`, `versioning_status`, `avif_autodetection`)
-- берут свои значения по умолчанию: приложение ими не пользуется, и
-- прописывать их значило бы фиксировать в миграции детали платформы, которые
-- она вправе менять сама.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'media',
  'media',
  false,           -- приватный: см. выше, на этом стоят все SELECT-политики
  104857600,       -- 100 MiB, как в 20260820130000
  array[
    'image/jpeg',
    'image/png',
    'image/webp',
    'image/heic',
    'image/heif',
    'video/mp4',        -- .mp4
    'video/quicktime',  -- .mov
    'video/x-m4v',      -- .m4v
    'video/3gpp',       -- .3gp
    'video/webm',       -- .webm
    'video/x-matroska'  -- .mkv
  ]
)
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;
