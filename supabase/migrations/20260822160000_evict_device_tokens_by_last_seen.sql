-- Вытеснение device_tokens начинает считать свежестью то, что ею является.
--
-- enforce_device_token_limit() (20260821180000) держит 19 строк с наибольшим
-- `created_at`. Тогда это читалось как «19 самых свежих» — и было им, пока
-- `created_at` был единственным временем в таблице.
--
-- 20260822130000 это изменила: `pin_device_token_timestamps()` НАМЕРЕННО
-- возвращает `created_at` к старому значению при каждом апсерте и ведёт
-- `updated_at` как «когда устройство последний раз выходило на связь».
-- То есть `created_at` теперь — дата ПЕРВОЙ регистрации этого токена и
-- больше не двигается никогда, а сортировка по ней означает «19 позже всех
-- заведённых», что не то же самое.
--
-- Чем это оборачивается. У человека телефон, зарегистрированный год назад и
-- открываемый каждый день (самый старый `created_at`, самый свежий
-- `updated_at`), плюс 19 строк, накопленных переустановками и планшетом за
-- последние месяцы. Двадцать первая регистрация вытесняет строку на
-- `offset 19` — то есть тот самый годовалый рабочий телефон, — а заведомо
-- мёртвые токены помоложе остаются. Пуши на основном устройстве замолкают до
-- следующего запуска приложения, и дренаж продолжает ходить в FCM по мёртвым
-- строкам, ради экономии на которых лимит и вводился.
--
-- Правка ровно в ключе сортировки. Всё остальное — ранний выход по дубликату
-- (`ON CONFLICT` арбитрируется ПОСЛЕ BEFORE INSERT, см. «Грабли» в CLAUDE.md),
-- `offset 19`, вытеснение вместо исключения — сохранено как было; тело взято
-- из 20260821180000, миграции, которая трогала эту функцию последней.
--
-- `fcm_token` вторым ключом остаётся: `updated_at` у двух регистраций в одной
-- транзакции совпадёт ровно так же, как совпадал `created_at`, а `offset`
-- считает по тому же порядку, что и `order by`, поэтому он обязан быть
-- детерминированным.
create or replace function public.enforce_device_token_limit()
returns trigger
language plpgsql
as $$
begin
  -- Повторная регистрация того же устройства: строку разрешит `ON CONFLICT`,
  -- в лимит она уже посчитана, вытеснять ради неё нечего.
  if exists (
    select 1 from public.device_tokens
    where user_id = new.user_id and fcm_token = new.fcm_token
  ) then
    return new;
  end if;

  -- Оставить место ровно под эту строку: держим 19 последних выходивших на
  -- связь, остальные уходят.
  delete from public.device_tokens d
   where d.user_id = new.user_id
     and (d.user_id, d.fcm_token) in (
       select d2.user_id, d2.fcm_token
         from public.device_tokens d2
        where d2.user_id = new.user_id
        order by d2.updated_at desc, d2.fcm_token desc
        offset 19
     );

  return new;
end;
$$;
