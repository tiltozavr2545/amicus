-- Идемпотентность отправки поста/комментария — без выдачи клиенту первичного ключа.
--
-- Задача: `.timeout()` в Dart не отменяет запрос, он лишь перестаёт его ждать.
-- На медленной, но живой сети вставка может закоммититься уже после того, как
-- клиент показал ошибку, а экраны при ошибке не чистят поле ввода — поэтому
-- естественный повтор («Опубликовать» ещё раз) слал второй insert с тем же
-- содержимым. Ни у `posts`, ни у `comments` нет ограничения уникальности,
-- так что получался настоящий дубль.
--
-- Первая (отвергнутая) реализация давала клиенту выбирать `id` и делала
-- `upsert(onConflict: 'id', ignoreDuplicates: true)`. Дубли она убирала, но
-- открывала оракул существования строки. `ON CONFLICT DO NOTHING` не отличает
-- «вставил» от «уже было» ни кодом ответа, ни телом: оба раза 2xx. А `id` —
-- глобальный ключ, поэтому конфликт мог произойти и с ЧУЖОЙ строкой. Зная id
-- поста, который RLS от него прячет (ровно тот сценарий, что описан в
-- 20260726130000: заблокированный сохраняет id-шники постов, которые видел до
-- блокировки), пользователь мог послать запрос с этим id и по тому, появился
-- ли у него собственный пост, узнать, жива ли ещё чужая строка — то есть
-- удалил ли автор пост. SELECT-политика ровно это и должна скрывать.
--
-- Здесь ключ идемпотентности отделён от первичного: `id` снова целиком
-- серверный (`gen_random_uuid()`), а клиент присылает `client_token` —
-- непрозрачный uuid своей попытки. Уникальность — составная,
-- `(author_id, client_token)`, и `author_id = auth.uid()` уже прибит
-- INSERT-политикой, поэтому конфликт физически возможен только с собственной
-- строкой вызывающего. Про чужие строки функция не отвечает ничего.
--
-- Индекс намеренно НЕ частичный (`where client_token is not null`), хотя так
-- было бы экономнее: частичный индекс PostgreSQL выводит в `ON CONFLICT`
-- только вместе с совпадающим предикатом `WHERE`, а PostgREST через
-- `on_conflict=` умеет передать лишь список колонок. Обычный unique-индекс
-- выводится по списку колонок, а NULL-ы в нём друг с другом не конфликтуют —
-- поэтому все уже существующие строки (у них `client_token is null`) под
-- ограничение не попадают и миграция не переписывает данные.
--
-- `client_token` заполняет клиент — это его смысл, — так что прибивать его в
-- INSERT-политике (как `created_at`/`deleted_at` в 20260726190000 и
-- 20260726160000) нечего: подделать им можно только собственную идемпотентность.

alter table public.posts add column client_token uuid;
alter table public.comments add column client_token uuid;

create unique index posts_author_id_client_token_key
  on public.posts (author_id, client_token);

create unique index comments_author_id_client_token_key
  on public.comments (author_id, client_token);
