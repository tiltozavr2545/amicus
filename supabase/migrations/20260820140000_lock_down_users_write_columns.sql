-- `public.users` — последняя таблица, до которой не дошёл приём из
-- 20260818130000: «серверную колонку клиент писать не должен».
--
-- Тот же дефолтный табличный грант Supabase, что уже чинили для
-- posts/comments (20260818130000), reactions (20260819130000),
-- favorite_users/device_tokens (20260819140000), post_media (20260819200000)
-- и profile_photos (20260819240000). UPDATE-политика на `users` проверяет
-- только `auth.uid() = id` — то есть «моя ли это строка», и ничего не говорит
-- о том, какие колонки в ней можно менять. Проверено на живой схеме:
-- `authenticated` имеет UPDATE на всех пяти колонках, включая две, которые
-- клиент не пишет никогда.
--
--   dislikes_disabled  флаг «не показывать мне дизлайки». 20260711120000
--                      прямо пишет, что кому его ставить — решает отдельный
--                      data-update, который «намеренно не попадает сюда»,
--                      и ни одна строка клиента в эту колонку не пишет. При
--                      живом гранте любой пользователь включал его себе сам
--                      обычным PATCH — то есть выдавал себе право, которого у
--                      него по замыслу нет.
--   created_at         возраст аккаунта. `enqueue_inactive_week_notifications()`
--                      (20260818190000) пропускает аккаунты моложе недели
--                      через `u.created_at < now() - interval '7 days'`;
--                      подделав колонку, эту проверку обходят сразу.
--
-- Ровно тот же выбор, что в 20260818130000: не пин по значению, а снятие
-- табличного гранта и перечисление колонок поимённо. Пин здесь и не построить
-- — `created_at` у существующей строки при обычном UPDATE не равен `now()`, а
-- `dislikes_disabled` сравнивать не с чем. Цена та же: список надо помнить при
-- добавлении колонки, зато забытая колонка оказывается закрытой, а не
-- открытой.
--
-- Что остаётся клиенту: `name` (экран профиля) и `avatar_path`. Последний
-- пишет не только `profile_repository.dart`, но и триггер
-- `sync_avatar_path_from_profile_photos()` (20260819240000) — он намеренно НЕ
-- `security definer`, то есть выполняется правами вызывающего, и без этого
-- гранта любая мутация галереи упала бы.
--
-- INSERT забирается целиком: строки в `users` создаёт только триггерная
-- `handle_new_user()` (20260708152508, `security definer`), а клиентская
-- INSERT-политика снята там же ещё тогда. Грант просто пережил её.
revoke insert, update on public.users from authenticated;
grant update (name, avatar_path) on public.users to authenticated;

-- `posts.text` и `comments.text` ограничены 5000 символами с 20260716120000,
-- а `name` — нет, хотя попадает в каждую строку ленты и в список знакомых
-- каждого знакомого. 100 символов с запасом покрывают любое настоящее имя
-- (на момент миграции самое длинное в базе — 16).
alter table public.users
  add constraint users_name_length check (char_length(name) <= 100);

-- Ограничение выше должно быть недостижимо на пути регистрации, а не
-- превращать длинное имя в непонятную ошибку: `handle_new_user()` пишет то,
-- что пришло в `raw_user_meta_data`, то есть значение, которое вообще не
-- проходило через экран приложения. Обрезаем там же, где уже обрабатываем
-- пустое имя (20260714120000) — по той же причине: это defence in depth для
-- регистрации мимо клиента.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.users (id, name)
  values (
    new.id,
    left(
      coalesce(nullif(trim(new.raw_user_meta_data ->> 'name'), ''), 'Без имени'),
      100
    )
  );
  return new;
end;
$$;
