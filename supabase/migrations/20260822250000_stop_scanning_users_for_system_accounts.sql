-- visible_author_ids() перестаёт искать системный аккаунт перебором users.
--
-- Функция отвечает на вопрос «чьи записи мне вообще можно показывать» и стоит
-- под SELECT-политиками posts, comments, post_media и под storage-политикой
-- фото постов — то есть вызывается на каждой ленте, на каждом экране
-- комментариев и на каждой подписи медиа-ссылки.
--
-- Ветку системного аккаунта в неё завела 20260818150000, когда единственным
-- способом узнать этот id была функция-предикат `is_system_account(uuid)`:
-- «пройди по users и спроси про каждую строку». С тех пор появился прямой
-- источник — `system_account_ids()` (20260821160000), а 20260822220000 сделала
-- его ЕДИНСТВЕННЫМ: теперь `is_system_account()` сама спрашивает у него. То
-- есть перебор таблицы остался просто по инерции — он ходит в users, чтобы
-- окольным путём получить константу, которая лежит рядом.
--
-- Замерено на живой схеме (EXPLAIN ANALYZE в откатываемой транзакции), тело
-- функции как есть:
--
--   Seq Scan on users … Filter: is_system_account(id), Rows Removed by Filter: 11
--
-- Двенадцать пользователей — это сегодня, и потому в миллисекундах разницы
-- почти нет. Важно не число, а форма: стоимость растёт вместе с числом
-- ЗАРЕГИСТРИРОВАННЫХ, хотя ответ ветки — короткий постоянный список, ни от
-- кого не зависящий. Ровно ту же форму — «вызов на каждую строку таблицы,
-- которая только растёт» — вычищала 20260726180000, выиграв на ленте 217 мс →
-- 3.5 мс; здесь она вернулась этажом ниже, внутри самой функции, которую та
-- миграция и написала.
--
-- Второй копией правила это не становится, а наоборот: ветка теперь читает тот
-- же и единственный источник, который проверяет `is_system_account()`.
--
-- Смысл слегка меняется в одном месте, и в лучшую сторону. Раньше ветка
-- отдавала id, только если под ним ЕСТЬ строка в users; теперь — как объявлено
-- в `system_account_ids()`. На выдачу это не влияет: `author_id` у постов,
-- комментариев и медиа — внешний ключ на users, так что несуществующий id всё
-- равно ни с чем не совпадёт, а объявленный системным аккаунт системным и
-- является по определению — это и есть смысл той функции.
--
-- Тело взято из 20260818150000 — миграции, которая трогала visible_author_ids()
-- последней (см. «Грабли» в CLAUDE.md про `create or replace`), — и отличается
-- от неё ровно одной строкой.

create or replace function public.visible_author_ids()
returns setof uuid
language sql
stable
security definer
set search_path = public
as $$
  select auth.uid()
  union
  select s from public.system_account_ids() s
  union
  select other.id
    from (
      select case when c.user_a_id = auth.uid() then c.user_b_id else c.user_a_id end as id
        from connections c
       where c.user_a_id = auth.uid() or c.user_b_id = auth.uid()
    ) other
   where public.is_author_visible(other.id);
$$;
