-- Ограничить device_tokens сверху: длина токена и число строк на пользователя.
--
-- До сих пор `fcm_token` был свободным `text` без длины и формата, а число
-- строк на пользователя не ограничивалось ничем — политика (20260818190000)
-- говорит только ЧЬЯ строка, а колоночный грант (20260819140000) только КАКИЕ
-- колонки. Один аутентифицированный пользователь мог одним батчем вставить
-- сколько угодно строк с мусорным токеном, и все прошли бы RLS.
--
-- Цена этого — не место в таблице, а дренаж очереди: одна строка outbox для
-- такого пользователя разворачивается в по одному запросу в FCM на каждый его
-- токен. Даже с пулом (20260821150000) десять тысяч мусорных токенов
-- растягивают прогон далеко за минуту, а значит возвращают наложение прогонов,
-- которое тот claim и закрывал, попутно сжигая квоту FCM.
--
-- ЛИМИТ ВЫТЕСНЯЕТ, А НЕ ПАДАЕТ — в отличие от лимитов на медиа
-- (20260819200000/20260819240000), и это осознанно другое решение для другой
-- ситуации. Там за вставкой стоит явное действие человека, которому нужно
-- показать «больше нельзя». Здесь регистрация устройства идёт fire-and-forget
-- из `registerDevice` и никакого экрана под собой не имеет: если бы триггер
-- начал кидать исключение, пользователь, накопивший лимит просроченных
-- токенов, просто молча перестал бы получать пуши навсегда. Токены к тому же
-- протухают сами (переустановка, очистка данных), а удаляются только когда FCM
-- ответит UNREGISTERED, то есть накопление здесь — штатный процесс, а не
-- обязательно злоупотребление. Поэтому самая старая строка уступает место
-- новой, и регистрация работает всегда.
--
-- 20 — с большим запасом относительно реального «телефон + планшет + пара
-- переустановок» и при этом жёсткий потолок.
--
-- Дубликат по `(user_id, fcm_token)` пропускается первым же условием. Это тот
-- самый случай из «Граблей»: `BEFORE INSERT` срабатывает ДО арбитража
-- `ON CONFLICT`, а клиентский `_upsertToken` шлётся заново при каждой смене
-- языка и на каждый запуск — то есть попадание в ветку DO UPDATE здесь не
-- редкость, а норма. Без этой проверки повторная регистрация того же
-- устройства вытесняла бы чужую строку на ровном месте.
--
-- `security definer` не нужен: триггер удаляет строки того же пользователя,
-- которому его собственная политика уже даёт и SELECT, и DELETE на них. Имена
-- квалифицированы `public.`, поэтому `set search_path` тоже не требуется —
-- та же схема, что у enforce_post_media_limit().

alter table public.device_tokens
  add constraint device_tokens_fcm_token_length
  check (char_length(fcm_token) between 64 and 4096);

create or replace function public.enforce_device_token_limit()
returns trigger
language plpgsql
as $$
begin
  -- Повторная регистрация того же устройства: строку разрешит `ON CONFLICT`,
  -- в лимит она уже посчитана, вытеснять ради неё нечего.
  if exists (
    select 1 from public.device_tokens
    where user_id = new.user_id and fcm_token = new.fcm_token
  ) then
    return new;
  end if;

  -- Оставить место ровно под эту строку: держим 19 самых свежих, остальные
  -- уходят. `offset` считает по тому же порядку, что и `order by`, поэтому
  -- сортировка обязана быть детерминированной — отсюда `fcm_token` вторым
  -- ключом (created_at у двух регистраций в одной транзакции совпадёт).
  delete from public.device_tokens d
   where d.user_id = new.user_id
     and (d.user_id, d.fcm_token) in (
       select d2.user_id, d2.fcm_token
         from public.device_tokens d2
        where d2.user_id = new.user_id
        order by d2.created_at desc, d2.fcm_token desc
        offset 19
     );

  return new;
end;
$$;

create trigger device_tokens_enforce_limit_before_insert
  before insert on public.device_tokens
  for each row execute function public.enforce_device_token_limit();
