-- Код приглашения становится отзываемым.
--
-- create_invite_link() (20260709134154) идемпотентна: если неиспользованный
-- код у владельца уже есть, она возвращает ЕГО, а не выпускает новый. Для
-- ретрая это правильно и так и задумывалось. Проблема в том, что другого
-- способа выпустить код нет, а кнопка на экране «Знакомства» после первого
-- нажатия подписана «Создать новый код» — и не создаёт: показывает ту же
-- строку.
--
-- Чем это плохо по существу. Код — это предъявительский секрет: кто его
-- активировал, тот стал Connection и получил ленту, профиль и галерею
-- владельца. Человек, отправивший код не в тот чат, не может сделать ровно
-- ничего: `invite_links_one_active_per_owner` (частичный уникальный индекс
-- `where not is_used`) не даёт завести вторую активную строку, а погасить
-- первую нечем — `is_used` ставит только activate_invite_link(), то есть
-- утёкший код гасится лишь тем, что его кто-то использует.
--
-- УДАЛЕНИЕ, А НЕ ПОМЕТКА `is_used`. Отозванный код должен читаться как
-- «такого кода нет» (PT404), а не «код уже использован» (PT409): второе —
-- неправда, и оно же подсказывает предъявителю, что код существовал и просто
-- опоздал. Заодно удаление освобождает частичный индекс под новую строку без
-- отдельного порядка операций. Строк учёта на этом не теряется: до активации
-- у invite_links нет ничего, кроме owner_id и самого кода.
--
-- Только неиспользованные: `and not is_used` — уже активированные строки это
-- история состоявшихся Connection (по ним же activate_invite_link() отвечает
-- PT409 повторному предъявителю), и ротация их не касается.
--
-- Отдельная функция, а не флаг у create_invite_link(): вызов, который может
-- обесценить уже разосланный секрет, обязан называться иначе, чем вызов,
-- который просто показывает текущий. Клиент зовёт эту только из ветки «код на
-- экране уже есть» и только после подтверждения.
create or replace function public.rotate_invite_link()
returns text
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_code text;
begin
  if auth.uid() is null then
    raise exception 'Not authenticated';
  end if;

  delete from invite_links
   where owner_id = auth.uid()
     and not is_used;

  v_code := encode(gen_random_bytes(5), 'hex');

  insert into invite_links (owner_id, code)
  values (auth.uid(), v_code);

  return v_code;
end;
$$;

-- Аргументов нет, всё внутри привязано к auth.uid() — то же условие для
-- гранта, что у create_invite_link() и остальных self-scoped RPC
-- (см. «Каждая функция в public — эндпоинт PostgREST» в CLAUDE.md).
revoke execute on function public.rotate_invite_link() from public, anon;
grant execute on function public.rotate_invite_link() to authenticated;
