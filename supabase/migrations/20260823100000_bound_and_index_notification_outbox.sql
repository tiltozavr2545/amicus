-- `notification_outbox` перестаёт расти вечно и получает индекс под свои
-- собственные запросы дедупликации.
--
-- Две отдельные проблемы, но лечатся вместе, потому что вторая без первой
-- лечится лишь наполовину.
--
-- 1. Индекс. Таблицу читают три места, и все три спрашивают её одинаково —
--    «был ли у ЭТОГО пользователя уже такой kind»:
--      * enqueue_post_notifications() (20260821100000) — guard дайджеста,
--        `where user_id = … and kind = 'digest' and created_at > window_start`.
--        Это самый горячий из трёх: он выполняется на КАЖДОЙ вставке поста и
--        по одному разу на каждого знакомого автора, то есть внутри цикла.
--      * enqueue_inactive_week_notifications() (20260819180000) — раз в сутки
--        на каждого пользователя.
--      * enqueue_app_update_notifications() (20260822120000) — на каждого
--        отставшего в момент рассылки.
--    Единственный существующий индекс — `notification_outbox_unsent_idx
--    (created_at) where sent_at is null` (20260818190000). Он про другое: под
--    него написан claim_notification_outbox(), который выбирает НЕотправленные
--    строки. Для запросов выше он бесполезен дважды: у него нет `user_id` в
--    ключе, и его частичное условие перестаёт выполняться через минуту после
--    вставки — drain-notification-outbox ходит раз в минуту и проставляет
--    `sent_at`, после чего строка из индекса выпадает совсем. Сейчас в таблице
--    62 строки и все 62 уже отправлены, то есть под guard дайджеста не работает
--    ни один индекс, и он читает таблицу целиком.
--
--    На 62 строках планировщик всё равно выберет seq scan, и мерить тут нечего
--    — форма важнее числа, ровно как в 20260822250000: стоимость guard'а растёт
--    вместе с ВСЕЙ историей уведомлений проекта, хотя вопрос у него узкий и
--    про одного человека. 20260821140000 закрывала такие же дыры по
--    `connections`/`favorite_users`/`posts`; сюда она не дошла.
--
-- 2. Ретенция. Строки не удаляет никто — ни один из четырёх cron-джобов
--    (operations.md). Поэтому даже с индексом таблица остаётся неограниченно
--    растущей: индекс убирает стоимость чтения, но не стоимость хранения и не
--    раздувание самого индекса.
--
--    Почему 90 суток, а не меньше. У таблицы два потребителя, которым нужна
--    ИСТОРИЯ, а не только свежие строки:
--      * guard дайджеста смотрит назад до `user_activity.last_active_at`
--        читателя — окно ничем сверху не ограничено. Если удалить строки
--        раньше, чем человек снова откроет приложение, guard перестанет
--        находить уже отправленный дайджест и пришлёт второй.
--      * дедупликация `app_update` идёт по `payload->>'build'` вообще без
--        временной границы — «одно уведомление на релиз».
--    90 суток покрывает первое с запасом (человек, не открывавший приложение
--    три месяца, получит лишний дайджест — это не цена, это скорее то, что
--    нужно) и обесценивает второе ровно там, где оно и так бессмысленно:
--    повторно рассылать «обновитесь» про сборку трёхмесячной давности никто
--    не станет.
--
--    Удаляются и неотправленные строки тоже. Drain ходит раз в минуту, так что
--    `sent_at is null` возрастом в 90 суток — это не «ещё не успели», это
--    мёртвая строка; доставлять пуш «новый пост» трёхмесячной давности хуже,
--    чем не доставлять.
--
-- Расписание — 05:10, в свободную минуту: остальные три разнесены на 03:40,
-- 12:00 и :20 каждого часа (operations.md).

create index notification_outbox_user_kind_created_idx
  on public.notification_outbox (user_id, kind, created_at desc);

create or replace function public.purge_notification_outbox()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_deleted integer;
begin
  with gone as (
    delete from notification_outbox
     where created_at < now() - interval '90 days'
    returning 1
  )
  select count(*) into v_deleted from gone;

  return v_deleted;
end;
$$;

-- Никому не выдана: чистка — дело крона, а аргументов у функции нет, поэтому
-- «отвечает только про себя» тут не спасает — она ПИШЕТ. См. «Каждая функция в
-- public — эндпоинт PostgREST» в CLAUDE.md.
revoke execute on function public.purge_notification_outbox() from public, anon, authenticated;

select cron.schedule(
  'purge-notification-outbox',
  '10 5 * * *',
  $$ select public.purge_notification_outbox(); $$
);
