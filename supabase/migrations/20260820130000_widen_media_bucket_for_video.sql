-- Приводит ограничения бакета `media` в соответствие с тем, что клиент реально
-- отправляет с 0.15.0 (видео в постах), и возвращает их в репозиторий.
--
-- 20260709134154 задала бакету `allowed_mime_types` из одних картинок и
-- `file_size_limit` 20 MiB — тогда это было верно, видео не существовало.
-- Когда появились видео-посты, ограничения правились руками в дашборде и в
-- миграции не попали: на момент этой правки живой бакет стоял на 100 MiB и
-- `video/mp4`, а `git` про это не знал ничего. Пересборка проекта из миграций
-- воспроизвела бы состояние, в котором видео не загружается вовсе.
--
-- Заодно закрывается дыра между этим списком и клиентом. Content-Type
-- storage_client не угадывает по содержимому, а берёт `lookupMimeType()` от
-- ИМЕНИ объекта (storage_client-2.6.0/lib/src/fetch.dart:27), а имя строит
-- `postMediaPath()` из настоящего расширения файла. Композер же принимает
-- `_videoExtensions = {mp4, mov, m4v, 3gp, webm, mkv}`, то есть шесть
-- расширений против одного разрешённого типа — выбранный в галерее `.mov`
-- (обычное дело для видео, снятого на iPhone и переехавшего на Android)
-- уезжал как `video/quicktime` и отлетал от бакета. Список ниже — ровно
-- отображение этих шести расширений в MIME по таблице пакета `mime`.
--
-- 100 MiB — уже действующее значение, не новое послабление: 60 секунд
-- (`_maxVideoDuration`) видео с телефона в 20 MiB не укладываются, что и было
-- причиной ручной правки. Постер видео — обычный JPEG рядом, он проходит по
-- `image/jpeg`, который в списке был с самого начала.
--
-- Это по-прежнему backstop, а не основной гейт: длительность режет композер,
-- а размер — здоровье бакета, не безопасность.
update storage.buckets
set file_size_limit = 104857600, -- 100 MiB
    allowed_mime_types = array[
      'image/jpeg',
      'image/png',
      'image/webp',
      'image/heic',
      'image/heif',
      'video/mp4',        -- .mp4
      'video/quicktime',  -- .mov
      'video/x-m4v',      -- .m4v
      'video/3gpp',       -- .3gp
      'video/webm',       -- .webm
      'video/x-matroska'  -- .mkv
    ]
where id = 'media';
