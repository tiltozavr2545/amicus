-- Один литерал системного аккаунта на весь сервер.
--
-- 20260821160000 завела system_account_ids() именно затем, чтобы id не жил в
-- двух местах: клиент перестал носить его в APK и стал спрашивать сервер. На
-- сервере же копий стало ровно две — is_system_account() (20260818150000) со
-- своим literal'ом и system_account_ids() со своим, — и они ничем не связаны.
--
-- Ротация аккаунта с правкой одной функции ничего не сломает громко:
--   * поехал только is_system_account() — посты нового аккаунта видны всем и
--     не шлют уведомлений, но fetchPage их из общей ленты больше не исключает,
--     и они лезут в ленту каждому;
--   * поехал только system_account_ids() — лента прячет аккаунт, который
--     is_author_visible() системным уже не считает, так что пасхалка на
--     переключателе темы открывает профиль, который никому не читается.
-- Ни то, ни другое не падает — это ровно тот класс расхождения, который
-- 20260821160000 и выводила.
--
-- Теперь набор один: system_account_ids() его объявляет, is_system_account()
-- по нему спрашивает.
--
-- Две мелочи, обе вынужденные:
--   * `immutable` -> `stable`: system_account_ids() читает не аргументы, она
--     `stable`, и immutable-функция не имеет права её звать. Проверено, что
--     ни один индекс и ни одно ограничение на is_system_account() не опирается
--     (иначе смена волатильности потребовала бы их перестроить).
--   * `exists (...)` вместо `p_id in (...)`: строгий boolean вместо
--     трёхзначного. `null in (…)` вернул бы null, и null с false стали бы
--     различимы снаружи — тот самый оракул, из-за которого
--     is_author_of_comment_visible() обернули в coalesce в 20260821130000.
--
-- Грант не трогается: `create or replace` не сбрасывает ACL, а
-- system_account_ids() уже выдана authenticated — единственной роли, которая
-- зовёт is_system_account() напрямую (SELECT-политика users). Все остальные
-- вызовы идут изнутри `security definer`-функций, то есть правами владельца.

create or replace function public.is_system_account(p_id uuid)
returns boolean
language sql
stable
set search_path = public
as $$
  select exists (
    select 1 from public.system_account_ids() as s where s = p_id
  );
$$;
