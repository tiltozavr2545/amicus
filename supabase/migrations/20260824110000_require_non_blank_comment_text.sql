-- `comments.text` наконец получает нижнюю границу — ту же, что `posts.text` и
-- `users.name` получили в 20260822200000.
--
-- Та миграция закрывала ровно этот класс («инвариант, который до сих пор
-- держался только клиентом») и до комментариев не дошла. Сверху текст ограничен
-- с 20260716120000 (`comments_text_length`, 5000 символов), снизу — ничем.
-- Единственная проверка на пустоту живёт в `_send()` (comments_screen.dart) как
-- `if (text.isEmpty) return`.
--
-- Поэтому `POST /rest/v1/comments` с `{"post_id":…,"author_id":<я>,"text":"   "}`
-- проходит и INSERT-политику, и CHECK. Строка после этого:
--   * рисуется пустой строкой в ветке у КАЖДОГО, кому виден пост;
--   * считается в `comment_summary()` — он отбрасывает только тромбстоуны
--     (`deleted_at is null`), а про пробелы ничего не знает, так что счётчик на
--     карточке в ленте показывает комментарий, которого не видно;
--   * дёргает `enqueue_comment_notifications()`, то есть за неё уходит пуш
--     «X прокомментировал(а) ваш пост» автору поста.
--
-- ТОМБСТОУН ОБЯЗАН ПРОЙТИ. `delete_own_comment()` (20260822140000) удаляет
-- комментарий с ответами не строкой, а затиранием: `set deleted_at = now(),
-- text = ''` — пустая строка тут не мусор, а само значение «текста больше нет,
-- ветка держится на этой строке». Поэтому условие не `btrim(text) <> ''`, а
-- дизъюнкция с `deleted_at`: оба поля выставляются одним UPDATE, так что на
-- момент проверки строка уже помечена удалённой.
--
-- Клиент под это правило подходит без изменений: `_send()` шлёт `text.trim()` и
-- выходит раньше, если он пуст. Сборкам в Play — тоже: та же проверка стоит в
-- 41-й и во всех предыдущих.
--
-- Живых нарушителей нет, проверено перед накатом (0 строк с `deleted_at is null
-- and btrim(text) = ''` из 10). Проверка повторена в самой миграции: накат
-- обязан упасть здесь, а не оставить `NOT VALID`-подобное состояние, в котором
-- часть строк правилу не соответствует.

do $$
declare
  v_bad bigint;
begin
  select count(*) into v_bad
    from public.comments c
   where c.deleted_at is null
     and btrim(c.text) = '';

  if v_bad > 0 then
    raise exception
      'comments: % blank row(s); fix them before applying this migration',
      v_bad;
  end if;
end
$$;

alter table public.comments
  add constraint comments_text_not_blank
  check (deleted_at is not null or btrim(text) <> '');
