-- Снять с роли `anon` дефолтные гранты Supabase на публичных таблицах.
--
-- `anon` — это роль незалогиненного вызывающего. Политик, которые бы к ней
-- относились, в схеме нет ни одной (все объявлены `to authenticated`), поэтому
-- RLS и так отклоняет для неё любой SELECT/INSERT/UPDATE/DELETE. Дырой это не
-- было — проверено симуляцией до правки. Убирается лишнее право, а не открытый
-- доступ.
--
-- Что здесь всё-таки не только про аккуратность: в наборе есть **TRUNCATE**, а
-- на TRUNCATE row-level security не распространяется в принципе — политики
-- фильтруют строки, а TRUNCATE не строчная операция. То есть у единственного
-- права из этого списка второго рубежа обороны нет вовсе, и держит его сейчас
-- ровно одно обстоятельство: PostgREST не отображает TRUNCATE ни на один
-- HTTP-глагол. Защищаться поверхностью API вместо привилегии — не то, на чём
-- стоит останавливаться, когда право попросту не нужно.
--
-- Что эти гранты вообще делают в схеме: это дефолт, который Supabase выдаёт
-- при создании проекта. Лучшее доказательство, что он не нужен, — `muted_users`
-- и `blocked_users`: они появились позже, обычной миграцией, и прав `anon` у
-- них нет ни одного, при этом всё работает. Здесь остальные шесть таблиц
-- приводятся к тому же виду.
--
-- Регистрация от этого не зависит: `public.users` наполняет триггерная
-- `handle_new_user()`, она `security definer` с владельцем `postgres`, то есть
-- выполняется с его правами, а не с правами вызывающего. Проверено перед
-- правкой. Экран сброса пароля тоже не читает RLS-таблицы (см. 0.6.0).
--
-- `service_role` и `authenticated` не трогаем.

revoke all on public.users from anon;
revoke all on public.posts from anon;
revoke all on public.comments from anon;
revoke all on public.connections from anon;
revoke all on public.invite_links from anon;
revoke all on public.reactions from anon;
