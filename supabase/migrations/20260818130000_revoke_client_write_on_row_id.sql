-- Закрыть оракул существования строки: отобрать у клиента право писать `id`.
--
-- 20260818120000 увела НАШ клиент с «клиент выбирает первичный ключ» на
-- `client_token`, и это правильная форма — но саму дыру она не закрывает.
-- Атакующий не пользуется нашим приложением, он шлёт запрос curl-ом, а право
-- писать `id` даёт дефолтный табличный грант Supabase (см. грабли в CLAUDE.md:
-- «Дефолтные гранты Supabase дают `authenticated` писать все колонки»).
--
-- Дыра воспроизведена на живой схеме симуляцией (роль `authenticated`,
-- `request.jwt.claims`, транзакция с rollback). Пользователь «Test User», не
-- знакомый с автором, пост которого RLS от него прячет:
--
--   can_select_hidden   = 0   -- SELECT-политика пост действительно скрывает
--   probe_known_landed  = 0   -- insert с id этого поста: тихо ничего, БЕЗ ошибки
--   probe_free_landed   = 1   -- insert со свободным id: строка создана
--
-- То есть по факту появления собственного поста вызывающий отличает «такой id
-- занят» от «свободен» и узнаёт, жива ли ещё чужая строка — ровно то, что
-- SELECT-политика обязана скрывать. `ON CONFLICT DO NOTHING` тут даже не
-- обязателен: без него дубликат поднимает 23505, и ошибка против успеха — тот
-- же самый оракул. Пока колонка доступна на запись, любой уникальный индекс,
-- который не сужен до самого вызывающего, отвечает на чужие вопросы.
--
-- Поэтому лечится не в политике, а в гранте: `id` заполняет сервер
-- (`gen_random_uuid()`), клиенту он не нужен ни в одном пути записи.
--
-- 20260726190000 этот приём для `created_at` сознательно отвергла — там был
-- доступен пин по значению (`created_at = now()`), который дешевле в
-- поддержке. Для `id` пина по значению не существует: он случаен по замыслу,
-- сравнивать его в `with check` не с чем. Так что здесь остаётся ровно тот
-- вариант, который та миграция называла дорогим — снять табличный INSERT и
-- перечислить остальные колонки поимённо.
--
-- Цена, названная там же, реальна: список надо поддерживать руками при каждой
-- новой колонке. Зато поведение по умолчанию переворачивается в безопасную
-- сторону — забытая колонка оказывается недоступной на запись, а не открытой
-- всему миру, — и это ровно тот дефолт, который граблям из CLAUDE.md нужен.
--
-- `created_at` и `deleted_at` остаются в списке намеренно: их уже прибивают по
-- значению политики из 20260726190000 и 20260726160000, и клиент, приславший
-- сегодняшний timestamp, по документации тех миграций проходит — забрав грант,
-- мы бы молча сломали описанное там поведение.

revoke insert on public.posts from authenticated;
grant insert (author_id, text, image_path, created_at, client_token)
  on public.posts to authenticated;

revoke insert on public.comments from authenticated;
grant insert (post_id, author_id, text, created_at, parent_comment_id,
              reply_to_id, deleted_at, client_token)
  on public.comments to authenticated;
