-- Правка гранта, без которой запись статуса регистрации не работала вовсе.
--
-- 20260913120000 выдала UPDATE поколоночно и НЕ включила `user_id` — по
-- очевидной на вид логике: ключ строки менять незачем. Логика верная, вывод
-- неверный: PostgREST разворачивает `upsert` в `ON CONFLICT DO UPDATE SET`
-- по ВСЕМ присланным колонкам, включая ту, по которой шёл конфликт. То есть
-- он всегда пишет `user_id = excluded.user_id`, даже когда значение то же
-- самое, и без права на эту колонку весь апсерт отбивается по 42501.
--
-- Симуляция этого не поймала, потому что в ней `SET` был написан руками — и
-- без `user_id`, раз менять его не требуется. Проверять надо ту форму
-- запроса, которую шлёт клиент, а не ту, которую удобно набрать: разница
-- между ними и была единственной причиной отказа. Наружу это не вылезло
-- вообще никак — `_recordStatus()` глотает свои ошибки намеренно (запись
-- диагностики не должна ронять регистрацию, которая могла пройти), так что
-- диагностика молча не работала.
--
-- Дыры не открывает: `with check (user_id = auth.uid())` у политики никуда
-- не делся, так что переписать строку на чужой id по-прежнему нельзя —
-- разрешено ровно то, что PostgREST и делает, записать в ключ то же
-- значение.
-- =====================================================================

grant update (user_id) on table public.push_registration_status to authenticated;
