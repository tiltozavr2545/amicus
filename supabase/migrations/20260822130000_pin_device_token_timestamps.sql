-- `updated_at` у device_tokens не работал, а `created_at` можно было подделать.
--
-- Две стороны одной дырки в правах. INSERT-грант на этой таблице колоночный
-- (20260819140000, расширен в 20260820110000 и 20260822110000), поэтому при
-- ДОБАВЛЕНИИ строки клиент до служебных колонок не дотягивается. А грант на
-- UPDATE остался табличным — то есть при ИЗМЕНЕНИИ своей строки клиент может
-- переписать в ней что угодно, включая обе даты.
--
-- Практического вреда сегодня нет: ни одно решение в схеме этих дат не
-- читает, подделанный `created_at` ничего не даёт. Это тот же класс
-- подделываемой серверной колонки, который в проекте закрывали уже шесть раз,
-- и закрывается он здесь скорее для порядка.
--
-- А вот вторая половина — настоящий баг. `updated_at` не обновлялся НИКОГДА:
-- клиентский `_upsertToken` переписывает строку на каждый запуск приложения и
-- на каждую смену языка, но в payload этой колонки нет, а `default now()`
-- срабатывает только при вставке. Проверено на живой базе перед правкой: у
-- всех строк `created_at = updated_at`, хотя приложение их регулярно трогает.
-- То есть колонка не «неточная», а просто врёт, и по ней нельзя было понять,
-- когда устройство последний раз выходило на связь.
--
-- Почему триггер, а не сужение гранта. Клиент пишет апсертом, и PostgREST
-- кладёт в SET ВСЕ колонки payload, а не только изменившиеся — включая
-- `user_id` и `fcm_token`. Колоночный грант на UPDATE отобрал бы права на
-- них и уронил бы весь запрос, то есть сломал бы регистрацию пушей целиком.
-- Ровно эта ситуация уже разбиралась для `reactions` (20260819150000), и
-- решение оттуда переносится дословно: триггер молча возвращает служебные
-- колонки к правильным значениям, грант остаётся широким, подделать нельзя.
--
-- `user_id` пинить не нужно — его держит `with check (user_id = auth.uid())`
-- в политике: перевесить свою строку на чужого пользователя она не даст.
-- `fcm_token` тоже: менять его в пределах СВОИХ строк безвредно, клиент и так
-- волен их удалять и создавать заново.
--
-- Триггер invoker, `security definer` не нужен: он не читает ни одной таблицы,
-- только NEW и OLD.

create or replace function public.pin_device_token_timestamps()
returns trigger
language plpgsql
as $$
begin
  new.created_at := old.created_at;
  new.updated_at := now();
  return new;
end;
$$;

create trigger device_tokens_pin_timestamps_before_update
  before update on public.device_tokens
  for each row execute function public.pin_device_token_timestamps();
