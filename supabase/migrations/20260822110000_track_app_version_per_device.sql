-- Устройство сообщает, какая версия приложения на нём стоит.
--
-- Нужно это ровно для одного: уведомление 'app_update' сейчас рассылать
-- некому и не за что — kind и настройка `notify_system_account` остались от
-- 20260820170000/20260820190000 без отправителя, и без знания версии любой
-- отправитель звал бы обновиться и тех, кто уже обновился.
--
-- Колонки живут на `device_tokens`, а не на `users`, потому что версия — это
-- свойство УСТАНОВКИ, а не человека: телефон и планшет одного пользователя
-- вполне могут стоять на разных версиях, и «пользователь на 0.16.4» —
-- бессмысленное утверждение. Заодно эта таблица уже апсертится на каждый
-- запуск приложения и на каждую смену языка (см. registerDevice), то есть
-- поле само поддерживается свежим без единого нового запроса.
--
-- Два поля, а не одно, и сравнивать надо по `app_build`:
--   * `app_build` — versionCode, монотонное целое, ровно то, по чему Play
--     считает сборку новее. Сравнение точное и не требует разбора строки.
--   * `app_version` — versionName ('0.16.4'), только чтобы глядя в таблицу
--     понимать, о чём речь. Никаких решений по нему не принимается: сравнение
--     строк вида '0.9.0' и '0.16.0' — классический способ ошибиться.
--
-- Оба nullable, и это не небрежность. Строки, записанные до этой миграции, и
-- любой клиент, который почему-то не прислал версию, останутся с NULL — и
-- потребитель обязан читать NULL как «версия древнее любой известной»:
-- приложение, не умеющее сообщить свою версию, по определению старее того,
-- которое умеет.
alter table public.device_tokens
  add column app_version text,
  add column app_build int;

alter table public.device_tokens
  add constraint device_tokens_app_build_positive
  check (app_build is null or app_build > 0);

-- Тот же формат, что и `versionName` в pubspec (`0.16.4`). Проверка нестрогая
-- намеренно — она отсекает мусор, а не валидирует семантику версии.
alter table public.device_tokens
  add constraint device_tokens_app_version_format
  check (app_version is null or app_version ~ '^[0-9]+\.[0-9]+\.[0-9]+$');

-- INSERT-грант колоночный с 20260819140000 (и расширен под locale в
-- 20260820110000), поэтому новые колонки надо добавить явно — иначе клиент их
-- просто не сможет записать. UPDATE-ветку апсерта трогать не нужно: грант на
-- UPDATE у таблицы табличный, а не колоночный.
revoke insert on public.device_tokens from authenticated;
grant insert (user_id, fcm_token, locale, app_version, app_build)
  on public.device_tokens to authenticated;
