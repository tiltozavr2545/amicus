-- Клиент перестаёт носить в себе копию списка системных аккаунтов.
--
-- Лента исключала системный аккаунт строкой
-- `query.neq('author_id', systemAccountId)` в feed_repository.dart, где
-- systemAccountId — литерал 'e5110c16-…', вкомпилированный в APK
-- (app/lib/shared/system_account_id.dart). На сервере то же знание живёт в
-- is_system_account() (20260818150000). Это ровно та форма, про которую
-- предупреждает «Грабли» в CLAUDE.md: одно правило, две копии — и копии
-- разъезжаются. Добавление второго системного аккаунта или ротация
-- существующего меняли бы серверный предикат, но не уже установленные
-- сборки: у всех них посты этого аккаунта так и остались бы в общей ленте,
-- и починить это можно было бы только релизом.
--
-- Здесь источником становится сервер: одна функция, отдающая тот же набор,
-- который проверяет is_system_account(). Клиент спрашивает её один раз за
-- сессию и держит компилированную константу лишь как запасной вариант на
-- случай, если запрос не прошёл (ленту нельзя ронять из-за фильтра).
--
-- Раскрытием это не является: профиль системного аккаунта и так специально
-- открыт всем аутентифицированным (20260818160000), так что его id ничего
-- нового не сообщает. Аргументов у функции нет — она отвечает только про
-- саму себя, что и есть условие для `grant execute … to authenticated`
-- (см. «Каждая функция в public — эндпоинт PostgREST» в CLAUDE.md).
--
-- is_system_account() остаётся точкой правды и дальше: функция ниже
-- перечисляет тот же набор, и при появлении второго аккаунта менять надо
-- обе — поэтому они лежат рядом и ссылаются друг на друга комментарием.

create or replace function public.system_account_ids()
returns setof uuid
language sql
stable
as $$
  -- Тот же набор, что проверяет is_system_account(p_id).
  select 'e5110c16-91e7-44ca-8075-348bca3efedd'::uuid;
$$;

revoke execute on function public.system_account_ids() from public, anon;
grant execute on function public.system_account_ids() to authenticated;
