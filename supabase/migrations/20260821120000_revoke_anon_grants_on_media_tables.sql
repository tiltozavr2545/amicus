-- Довести post_media и profile_photos до того же вида, к которому
-- 20260818140000 привела остальные восемь таблиц.
--
-- Обе таблицы созданы ПОСЛЕ той миграции (20260819200000 и 20260819240000) и
-- потому снова получили дефолтные гранты Supabase для роли `anon`:
-- на момент этой миграции у обеих —
-- DELETE, INSERT, REFERENCES, SELECT, TRIGGER, TRUNCATE, UPDATE. Проверено
-- запросом к information_schema.role_table_grants: во всём public это
-- единственные две таблицы, где у `anon` вообще что-то есть.
--
-- Дырой это, как и в 20260818140000, не является: политик для `anon` нет ни
-- одной (все объявлены `to authenticated`), поэтому RLS отклоняет любой
-- SELECT/INSERT/UPDATE/DELETE. Аргумент тот же, что и там, и он касается
-- ровно одного права из списка: **на TRUNCATE row-level security не
-- распространяется в принципе** — политики фильтруют строки, а TRUNCATE не
-- строчная операция. Держит его сейчас единственное обстоятельство: PostgREST
-- не отображает TRUNCATE ни на один HTTP-глагол. Для таблиц, в которых лежат
-- все медиа постов и все фото профилей, полагаться на это не стоит.
--
-- `revoke insert … from authenticated` в обеих исходных миграциях
-- (20260819200000:87, 20260819240000:62) — про другое: там сужаются права
-- залогиненного пользователя до колоночных грантов. Роль `anon` они не
-- трогают.

revoke all on public.post_media from anon;
revoke all on public.profile_photos from anon;
